"""Write generated/design/table_deviations.tex from the D-0nn headings of DEVIATIONS.md at frozen-v1 (fallback main)."""
import re

from _common import PAPER, resolve_ref, show, tex_escape, write_generated


def main() -> None:
    ref, _ = resolve_ref()
    md = show(ref, "DEVIATIONS.md").decode("utf-8")
    rows = []
    for m in re.finditer(r"^## (D-\d{3}) [\u2014-]+ (\d{4}-\d{2}-\d{2}) \(([^)]*)\): (.*)$", md, flags=re.M):
        rows.append(m.groups())
    if not rows:
        raise SystemExit("deviations_table: no D-0nn headings parsed")
    lines = [f"% Generated by tools/deviations_table.py from DEVIATIONS.md at {ref}. Do not edit.",
             r"\begin{tabularx}{\linewidth}{llX}", r"\toprule", r"ID & Date & Timing and change \\", r"\midrule"]
    for i, d, t, title in rows:
        lines.append(f"{i} & {d} & {tex_escape(title)} ({tex_escape(t)}) \\\\")
    lines += [r"\bottomrule", r"\end{tabularx}"]
    write_generated(PAPER / "generated/design/table_deviations.tex", "\n".join(lines) + "\n")
    print(f"deviations_table: {len(rows)} rows")


if __name__ == "__main__":
    main()
