"""Write generated/design/table_cells.tex (Table 1: the 11 cells) from experiment.yaml at frozen-v1 (fallback main) and data/cell_roles.yaml."""
import yaml

from _common import PAPER, resolve_ref, show, tex_escape, write_generated

RUNBOOK = {"V0": "none", "V-POLICY": "rule against unverified claims", "V-R1": "log introduction",
           "V-R1-DEDUPE": "log introduction; de-duplication sentence"}
C2 = {"C2.R": "routine aside", "C2.CN": "concern", "CLAIM": "claim", "CLAIM+FORGED": "claim; receipt-style line typed in post"}


def main() -> None:
    ref, _ = resolve_ref()
    exp = yaml.safe_load(show(ref, "configs/experiment.yaml"))
    roles = yaml.safe_load((PAPER / "data/cell_roles.yaml").read_text())
    core = {c["cell"]: c["count"] for c in exp["phases"]["core"]["arms"][0]["cells"]}
    son = {c["cell"]: c["count"] for c in exp["phases"]["sonnet"]["arms"][0]["cells"]}
    lines = [f"% Generated by tools/cells_table.py from configs/experiment.yaml at {ref}. Do not edit.",
             r"\begin{tabularx}{\linewidth}{ll>{\raggedright\arraybackslash}p{0.17\linewidth}>{\raggedright\arraybackslash}p{0.17\linewidth}rr>{\raggedright\arraybackslash}X}", r"\toprule",
             r"Cell & World & Extra runbook paragraph & C's round-2 post & Haiku shifts & Sonnet shifts & Role \\", r"\midrule"]
    for name in exp["core_cells"]:
        c = exp["cells"][name]
        c2 = C2[c["c2"]] + ("; real note filed" if c["c_note"] else "")
        lines.append(f"\\cell{{{tex_escape(name)}}} & {c['world']} & {RUNBOOK[c['runbook']]} & {c2} & {core.get(name, 0)} & "
                     f"{son.get(name, '---')} & {tex_escape(roles[name])} \\\\")
    lines += [r"\bottomrule", r"\end{tabularx}"]
    write_generated(PAPER / "generated/design/table_cells.tex", "\n".join(lines) + "\n")
    print("cells_table: ok")


if __name__ == "__main__":
    main()
