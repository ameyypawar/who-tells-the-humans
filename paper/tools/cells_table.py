"""Write generated/design/table_cells.tex (Table 1: the 11 cells) from experiment.yaml at frozen-v1 (fallback main) and data/cell_roles.yaml.
One line per cell, so the float stays small (plan 49 budget: about 0.3 page)."""
import yaml

from _common import PAPER, resolve_ref, show, tex_escape, write_generated

RUNBOOK = {"V0": "---", "V-POLICY": "one-line rule", "V-R1": "log sentence", "V-R1-DEDUPE": "log sentence, duplicate cost"}
C2 = {"C2.R": "routine aside", "C2.CN": "concern", "CLAIM": "claim", "CLAIM+FORGED": "claim + typed receipt-style line"}


def main() -> None:
    ref, _ = resolve_ref()
    exp = yaml.safe_load(show(ref, "configs/experiment.yaml"))
    roles = yaml.safe_load((PAPER / "data/cell_roles.yaml").read_text())
    core = {c["cell"]: c["count"] for c in exp["phases"]["core"]["arms"][0]["cells"]}
    son = {c["cell"]: c["count"] for c in exp["phases"]["sonnet"]["arms"][0]["cells"]}
    lines = [f"% Generated by tools/cells_table.py from configs/experiment.yaml at {ref}. Do not edit.",
             r"\begin{tabular}{@{}lllllrr@{}}", r"\toprule",
             r" & & Runbook & & & \multicolumn{2}{c@{}}{Shifts} \\", r"\cmidrule(l){6-7}",
             r"Cell & World & adds & C's round-2 post & Role & Haiku & Sonnet \\", r"\midrule"]
    for name in exp["core_cells"]:
        c = exp["cells"][name]
        c2 = C2[c["c2"]] + ("; real note filed" if c["c_note"] else "")
        lines.append(f"\\cell{{{tex_escape(name)}}} & {c['world']} & {RUNBOOK[c['runbook']]} & {c2} & {tex_escape(roles[name])} & "
                     f"{core.get(name, 0)} & {son.get(name, '---')} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write_generated(PAPER / "generated/design/table_cells.tex", "\n".join(lines) + "\n")
    print("cells_table: ok")


if __name__ == "__main__":
    main()
