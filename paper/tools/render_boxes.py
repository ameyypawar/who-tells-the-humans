"""Write generated/design/boxes/receipt_vs_noreceipt_r2.tex: round-2 board and log excerpt, RECEIPT beside NO-RECEIPT.

Source: tests/golden/{RECEIPT,NO-RECEIPT}_r2.txt at frozen-v1 (fallback main, PROVISIONAL). The golden files are rendered at
level L2 with the public paraphrase; at a frozen level F other than L2, V's round-2 line is replaced by V2.<F> (below),
and where runs/wtth.sqlite exists each full render must equal a stored core round-2 prompt of its cell byte for byte
(`wtth render` renders an empty state, without the board, so the stored prompts are the reference).
FORGED is never rendered here: it is described by mechanism only.
"""
import sys

import yaml

from _common import PAPER, hashes, resolve_ref, sha256, show, stored_prompt_matches, write_generated


def split(text: str):
    lines = text.splitlines()
    i = next(k for k, l in enumerate(lines) if l.startswith("#ops-board"))
    j = next(k for k, l in enumerate(lines) if l.startswith("#escalation-log"))
    r = next(k for k, l in enumerate(lines) if l.startswith("YOUR RECORD SO FAR"))
    return lines[i:j], lines[j:r]


def main() -> None:
    ref, prov = resolve_ref()
    exp = yaml.safe_load(show(ref, "configs/experiment.yaml"))
    g = {c: show(ref, f"tests/golden/{c}_r2.txt").decode("utf-8") for c in ("RECEIPT", "NO-RECEIPT")}
    (b1, l1), (b2, l2) = split(g["RECEIPT"]), split(g["NO-RECEIPT"])
    if b1 != b2:
        sys.exit("render_boxes: RECEIPT and NO-RECEIPT boards differ; the box assumes an identical board")
    for t in g.values():
        if "{" in t and "PRIVATE" in t.upper():
            sys.exit("render_boxes: unexpected private marker in a golden file")
    level = exp.get("frozen_level") or "L2"
    tag = "PROVISIONAL (golden files, level L2; frozen_level unset)" if (prov or not exp.get("frozen_level")) else f"level {level}"
    if level != "L2":
        # The golden renders are at L2. In the round-2 digest only V's round-2 line depends on the level (V1, B and C
        # lines do not), so the frozen-level render is the golden one with V2.L2 replaced by V2.<level>, both taken
        # from the hash-checked prompts/scripted_lines.md. Each golden file must hold the L2 line exactly once.
        raw = show(ref, "prereg/prompts/scripted_lines.md")
        if sha256(raw) != hashes(ref)["files"]["prompts/scripted_lines.md"]:
            sys.exit("render_boxes: SHA-256 of prompts/scripted_lines.md differs from configs/prereg_hashes.json")
        lines = dict(l.split(" :: ", 1) for l in raw.decode("utf-8").splitlines() if " :: " in l)
        v_l2, v_f = lines["V2.L2"].strip(), lines[f"V2.{level}"].strip()
        for c in g:
            if g[c].count(v_l2) != 1:
                sys.exit(f"render_boxes: V2.L2 not found exactly once in tests/golden/{c}_r2.txt")
            g[c] = g[c].replace(v_l2, v_f)
        (b1, l1), (b2, l2) = split(g["RECEIPT"]), split(g["NO-RECEIPT"])
        tag = f"level {level}: golden L2 renders with V's round-2 line replaced by V2.{level} from prompts/scripted_lines.md"
        for c in g:
            hits = stored_prompt_matches(g[c].rstrip("\n"), c, level)
            if hits == []:
                sys.exit(f"render_boxes: the {c} render at {level} equals no stored core round-2 prompt")
            if hits:
                print(f"render_boxes: {c} at {level} is byte-identical to {len(hits)} stored core round-2 prompts")
    v = lambda ls: "\\begin{Verbatim}[fontsize=\\scriptsize,breaklines=true,breakanywhere=true]\n" + "\n".join(ls).rstrip() + "\n\\end{Verbatim}"
    # Excerpt: the board header, a marker for the routine round-1 posts, and the round-2 posts (V's split and C's line).
    # The full digests are in Appendix B; the box only has to show what differs between cells and what sits next to it.
    bl = [l for l in b1 if l.strip()]
    keep = [bl[0], "[...]"] + bl[-2:] if len(bl) > 4 else bl
    out = [f"% Generated by tools/render_boxes.py from tests/golden at {ref}; {tag}. Do not edit.",
           r"\begin{center}\begin{lrbox}{\wtthbox}\begin{minipage}{0.97\linewidth}",
           r"{\footnotesize\textsf{Round-2 digest, board excerpt (identical in both cells):}}\par\smallskip", v(keep),
           r"\smallskip\hrule\smallskip",
           r"\begin{minipage}[t]{0.49\linewidth}{\footnotesize\textsf{\cell{RECEIPT}: log at the round-2 digest}}\par", v(l1), r"\end{minipage}\hfill",
           r"\begin{minipage}[t]{0.49\linewidth}{\footnotesize\textsf{\cell{NO-RECEIPT}: log at the round-2 digest}}\par", v(l2), r"\end{minipage}",
           r"\end{minipage}\end{lrbox}\fbox{\usebox{\wtthbox}}\end{center}"]
    write_generated(PAPER / "generated/design/boxes/receipt_vs_noreceipt_r2.tex", "\n".join(out) + "\n")
    print("render_boxes: ok", tag)


if __name__ == "__main__":
    main()
