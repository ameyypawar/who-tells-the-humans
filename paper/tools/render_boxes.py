"""Write generated/design/boxes/receipt_vs_noreceipt_r2.tex: round-2 board and log excerpt, RECEIPT beside NO-RECEIPT.

Source: tests/golden/{RECEIPT,NO-RECEIPT}_r2.txt at frozen-v1 (fallback main, PROVISIONAL). The golden files are rendered at
level L2 with the public paraphrase. LEAD-REVIEW: if the frozen level F is not L2, re-render with `wtth render` after the freeze.
FORGED is never rendered here: it is described by mechanism only.
"""
import sys

import yaml

from _common import PAPER, resolve_ref, show, write_generated


def split(text: str):
    lines = text.splitlines()
    i = next(k for k, l in enumerate(lines) if l.startswith("#ops-board"))
    j = next(k for k, l in enumerate(lines) if l.startswith("#escalation-log"))
    r = next(k for k, l in enumerate(lines) if l.startswith("YOUR RECORD SO FAR"))
    return lines[i:j], lines[j:r]


def main() -> None:
    ref, prov = resolve_ref()
    exp = yaml.safe_load(show(ref, "configs/experiment.yaml"))
    g = {c: show(ref, f"tests/golden/{c}_r2.txt").decode("utf-8") for c in ("RECEIPT", "NO-RECEIPT")}
    (b1, l1), (b2, l2) = split(g["RECEIPT"]), split(g["NO-RECEIPT"])
    if b1 != b2:
        sys.exit("render_boxes: RECEIPT and NO-RECEIPT boards differ; the box assumes an identical board")
    for t in g.values():
        if "{" in t and "PRIVATE" in t.upper():
            sys.exit("render_boxes: unexpected private marker in a golden file")
    level = exp.get("frozen_level") or "L2"
    tag = "PROVISIONAL (golden files, level L2; frozen_level unset)" if (prov or not exp.get("frozen_level")) else f"level {level}"
    v = lambda ls: "\\begin{Verbatim}[fontsize=\\scriptsize,breaklines=true,breakanywhere=true]\n" + "\n".join(ls).rstrip() + "\n\\end{Verbatim}"
    out = [f"% Generated by tools/render_boxes.py from tests/golden at {ref}; {tag}. Do not edit.",
           r"\begin{center}\begin{lrbox}{\wtthbox}\begin{minipage}{0.97\linewidth}",
           r"{\footnotesize\textsf{Round-2 digest, identical in both cells (board):}}\par\smallskip", v(b1),
           r"\smallskip\hrule\smallskip",
           r"\begin{minipage}[t]{0.49\linewidth}{\footnotesize\textsf{\cell{RECEIPT}: log at the round-2 digest}}\par", v(l1), r"\end{minipage}\hfill",
           r"\begin{minipage}[t]{0.49\linewidth}{\footnotesize\textsf{\cell{NO-RECEIPT}: log at the round-2 digest}}\par", v(l2), r"\end{minipage}",
           r"\end{minipage}\end{lrbox}\fbox{\usebox{\wtthbox}}\end{center}"]
    write_generated(PAPER / "generated/design/boxes/receipt_vs_noreceipt_r2.tex", "\n".join(out) + "\n")
    print("render_boxes: ok", tag)


if __name__ == "__main__":
    main()
