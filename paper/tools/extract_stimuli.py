"""Write generated/design/stimuli.tex (\\wtthStim...) and generated/design/prompts/*.tex from the prompt files.

Source: prereg/prompts/*.md at frozen-v1 (fallback main, PROVISIONAL). Each file's SHA-256 is checked against
configs/prereg_hashes.json at the same ref; a mismatch stops the build. Only public files are read (never prereg/private).
V's lines use the frozen clarity level F (frozen_level; L2, the level of tests/golden, while it is unset).

SB-3 (the rendered example, round 2 of a RECEIPT shift) was written into system_base.md at L2, before G1 froze F = L3.
Appendix B prints witness-visible text as sent, so the block is shown at F: V's round-2 line V2.L2 is replaced by
V2.<F> from the hash-checked scripted_lines.md (in this digest only V's round-2 line depends on the level), and, where
runs/wtth.sqlite exists, the result must equal a stored core RECEIPT round-2 prompt byte for byte or the build stops
(paper review 2, M7).
"""
import re
import sys

import yaml

from _common import PAPER, hashes, resolve_ref, sha256, show, stored_prompt_matches, tex_escape, write_generated

FILES = ["system_base", "runbook", "tools", "scripted_lines", "debrief", "judge_rubric"]


def blocks(md: str):
    """[(heading, text)] for each ```text fence, heading = the last ##/### line before it."""
    out, head, cur, inside = [], "", [], False
    for line in md.splitlines():
        if not inside and re.match(r"^#{2,3} ", line):
            head = line.lstrip("# ").strip()
        if line.startswith("```"):
            if inside:
                out.append((head, "\n".join(cur)))
                cur = []
            inside = not inside
            continue
        if inside:
            cur.append(line)
    return out


def lines_dict(bs):
    d = {}
    for _, t in bs:
        for line in t.splitlines():
            m = re.match(r"^(\S+)\s*::\s*(.*)$", line)
            if m:
                d[m.group(1)] = m.group(2).strip()
    return d


def one(rx: str, text: str, what: str) -> str:
    m = re.search(rx, text)
    if not m:
        sys.exit(f"extract_stimuli: cannot find {what}")
    return m.group(1) if m.groups() else m.group(0)


def main() -> None:
    ref, prov = resolve_ref()
    h = hashes(ref)["files"]
    src, shas = {}, {}
    for f in FILES:
        raw = show(ref, f"prereg/prompts/{f}.md")
        if sha256(raw) != h[f"prompts/{f}.md"]:
            sys.exit(f"extract_stimuli: SHA-256 of prompts/{f}.md at {ref} differs from configs/prereg_hashes.json")
        src[f], shas[f] = raw.decode("utf-8"), sha256(raw)
    exp = yaml.safe_load(show(ref, "configs/experiment.yaml"))
    level = exp.get("frozen_level") or "L2"
    B = {f: blocks(src[f]) for f in FILES}
    sl = lines_dict(B["scripted_lines"])
    sb3_note = sb3_at_level(B, sl, level)
    sb1 = next(t for hd, t in B["system_base"] if hd.startswith("SB-1"))
    rb = {hd.split(":")[0].split(" ")[0]: t for hd, t in B["runbook"]}
    notify = next(t for hd, t in B["tools"] if hd.startswith("3 notify_ops"))
    logfmt = next(t for hd, t in B["tools"] if hd.startswith("5 Escalation log line"))
    d1 = next(t for hd, t in B["debrief"] if hd.startswith("D1"))
    d2 = next(t for hd, t in B["debrief"] if hd.startswith("D2"))
    S: dict[str, str] = {}
    S["SystemStaffed"] = one(r"(The desk is staffed by AI agents\.)", sb1, "system staffed sentence")
    S["SystemOps"] = one(r"(Ops is the human operations team that runs the desk\.)", sb1, "system ops sentence")
    S["RuleSecondApproval"] = one(r"(Refunds over \$5,000 need a second approval from an operator before they are released\.)", rb["RB-BASE"], "rule")
    S["Policy"], S["ROne"], S["Dedupe"] = rb["RB-POLICY"], rb["RB-R1"], rb["RB-DEDUPE"]
    for n, k in (("VTwoF", "V2"), ("VThreeF", "V3"), ("VFourF", "V4")):
        S[n] = sl[f"{k}.{level}"]
    S["VTwoBN"] = sl["V2.BN"]
    S["CTwoR"], S["CTwoCN"], S["CTwoPOne"] = sl["C2.R"], sl["C2.CN"], sl["C2.P1"]
    S["CNoteSubject"], S["CNoteMessage"] = sl["subject"], sl["message"]
    S["NotifyOpsDesc"] = one(r"(?m)^description: (.*)$", notify, "notify_ops description")
    S["ReplyNotify"] = one(r"(?m)^reply: (.*)$", notify, "notify_ops reply")
    S["LogLine"] = one(r"(?m)^(E-\d{4} \| .*)$", logfmt, "log line")
    S["LogEmpty"] = one(r"`(No entries\.)`", src["tools"], "empty log text")
    S["DOne"] = d1.strip()
    S["DTwo"] = d2.strip().replace("\n", " ")
    S["LevelUsed"] = level
    S["Provisional"] = "yes" if (prov or not exp.get("frozen_level")) else "no"
    for f in FILES:
        S["Sha" + "".join(p.capitalize() for p in f.split("_"))] = shas[f]
    lines = ["% Generated by tools/extract_stimuli.py. Do not edit.",
             f"% source ref: {ref}; frozen_level in config: {exp.get('frozen_level')}; level used for V lines: {level}"]
    for k, v in S.items():
        body = v if k.startswith("Sha") or k in ("LevelUsed", "Provisional") else tex_escape(v)
        lines.append(rf"\newcommand{{\wtthStim{k}}}{{{body}}}")
    write_generated(PAPER / "generated/design/stimuli.tex", "\n".join(lines) + "\n")
    for f in FILES:
        parts = [f"% Generated by tools/extract_stimuli.py from prereg/prompts/{f}.md at {ref}. Do not edit.",
                 rf"\noindent\textit{{Source: \texttt{{prompts/{tex_escape(f)}.md}}, SHA-256 \texttt{{{shas[f][:16]}}}\ldots}}\par"]
        prev = None
        for hd, t in B[f]:
            assert "\\end{wtthverb}" not in t
            head = rf"\paragraph{{{tex_escape(hd)}}}" + "\n" if hd != prev else ""   # one heading per run of blocks
            prev = hd
            note = sb3_note + "\n" if (f == "system_base" and hd.startswith("SB-3") and sb3_note) else ""
            parts.append(head + note + "\\begin{wtthverb}\n" + t + "\n\\end{wtthverb}")
        write_generated(PAPER / f"generated/design/prompts/{f}.tex", "\n".join(parts) + "\n")
    write_preexisting(ref)
    print(f"extract_stimuli: {len(S)} macros, {len(FILES)} prompt files from {ref}, level {level}")


SB3_LEVEL = "L2"     # the level SB-3 was written at (system_base.md, before G1)


def sb3_at_level(B: dict, sl: dict, level: str) -> str:
    """Re-render SB-3 in B["system_base"] (in place) at `level` and return the note printed above it ("" at L2)."""
    i = next(k for k, (hd, _) in enumerate(B["system_base"]) if hd.startswith("SB-3"))
    hd, t = B["system_base"][i]
    if level == SB3_LEVEL:
        return ""
    old, new = sl[f"V2.{SB3_LEVEL}"], sl[f"V2.{level}"]
    if t.count(old) != 1:
        sys.exit(f"extract_stimuli: V2.{SB3_LEVEL} is not in SB-3 exactly once")
    t = t.replace(old, new)
    hits = stored_prompt_matches(t, "RECEIPT", level)
    if hits is None:
        print("extract_stimuli: SB-3 not checked against stored prompts (runs/wtth.sqlite absent)")
    elif not hits:
        sys.exit(f"extract_stimuli: SB-3 at {level} equals no stored core RECEIPT round-2 prompt")
    else:
        print(f"extract_stimuli: SB-3 at {level} is byte-identical to {len(hits)} stored core RECEIPT round-2 prompts "
              f"(seed, slot): {hits}")
    B["system_base"][i] = (hd, t)
    return (rf"\noindent\textit{{Shown at the frozen level {level}, as sent. The pre-registered example was rendered at "
            rf"{SB3_LEVEL} before G1 froze the level; in this digest only V's round-2 line depends on the level, and it "
            rf"is set to V2.{level}. The text equals, byte for byte, the round-2 prompt the core sent to a "
            rf"\textup{{\cell{{RECEIPT}}}} witness.}}\par")


def write_preexisting(ref: str) -> None:
    """generated/design/prereg_preexisting.tex: PREREG.md section 20 word for word (Appendix C.2), hash-checked."""
    raw = show(ref, "prereg/PREREG.md")
    if sha256(raw) != hashes(ref)["files"]["PREREG.md"]:
        sys.exit(f"extract_stimuli: SHA-256 of prereg/PREREG.md at {ref} differs from configs/prereg_hashes.json")
    m = re.search(r"^## 20 Preexisting-work disclosure\n(.*?)(?=^---|^## 21 )", raw.decode("utf-8"), flags=re.S | re.M)
    if not m:
        sys.exit("extract_stimuli: cannot find PREREG section 20")
    body = m.group(1).strip("\n")
    assert "\\end{wtthverb}" not in body
    write_generated(PAPER / "generated/design/prereg_preexisting.tex",
                    f"% Generated by tools/extract_stimuli.py from prereg/PREREG.md section 20 at {ref}. Do not edit.\n"
                    "\\begin{wtthverb}\n" + body + "\n\\end{wtthverb}\n")


if __name__ == "__main__":
    main()
