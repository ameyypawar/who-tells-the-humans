"""Narrow Table 2 (plan 49 section 2.7 item 13, built paper-side as a smallest faithful choice).
Reads the analysis export generated/analysis/tables/table_hypotheses.csv (every cell is generated; nothing typed here) and writes
generated/derived/table_hypotheses_main.tex with the Cells (k/n) and Status columns dropped, so it fits the text width.
Usage: table2_narrow.py [csv_in] [tex_out]
LEAD-REVIEW: the lead may instead add table_hypotheses_main.tex to wtth.analysis.tables (then delete this tool).
"""
import csv
import sys
from pathlib import Path

from _common import PAPER, tex_escape, write_generated

M = {"−": r"\ensuremath{-}", "±": r"\ensuremath{\pm}", "<": r"\textless{}", ">": r"\textgreater{}"}


def esc(s: str) -> str:
    return "".join(M.get(c, tex_escape(c)) for c in s)


def main() -> None:
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else PAPER / "generated/analysis/tables/table_hypotheses.csv"
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else PAPER / "generated/derived/table_hypotheses_main.tex"
    if not src.exists():
        print(f"table2_narrow: {src} not found (placeholder build), skipped")
        return
    rows = list(csv.reader(src.open(encoding="utf-8")))
    h = rows[0]
    keep = [h.index(c) for c in ("Hypothesis", "Contrast", "Diff. (pp)", "95% CI (pp)", "Decision")]
    lines = [f"% Generated by tools/table2_narrow.py from {src.name}. Do not edit.",
             r"\begin{tabularx}{\linewidth}{l>{\raggedright\arraybackslash}Xrr>{\raggedright\arraybackslash}X}", r"\toprule",
             " & ".join(esc(h[i]) for i in keep) + r" \\", r"\midrule"]
    for r in rows[1:]:
        lines.append(" & ".join(esc(r[i]) for i in keep) + r" \\")
    lines += [r"\bottomrule", r"\end{tabularx}"]
    write_generated(out, "\n".join(lines) + "\n")
    print(f"table2_narrow: {out}")


if __name__ == "__main__":
    main()
