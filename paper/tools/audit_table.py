"""Write generated/design/table_oss_audit.tex and audit.tex (\\wtthAudit...) from data/oss_audit.csv."""
import csv

from _common import PAPER, tex_escape, write_generated

W = {0: "none", 1: "one", 2: "two", 3: "three", 4: "four", 5: "five", 6: "six", 7: "seven", 8: "eight", 9: "nine",
     10: "ten", 11: "eleven", 12: "twelve", 13: "thirteen", 14: "fourteen", 15: "fifteen"}


def main() -> None:
    rows = list(csv.DictReader((PAPER / "data/oss_audit.csv").open(encoding="utf-8")))
    n = len(rows)
    cnt = lambda col, v: sum(r[col] == v for r in rows)
    full, part, ch = cnt("peers_can_verify", "Yes"), cnt("peers_can_verify", "Partial"), cnt("channel_written_receipt", "Yes")
    esc_yes, esc_part = cnt("escalation_to_human", "Yes"), cnt("escalation_to_human", "Partial")
    unchecked = cnt("quote_rechecked", "no")
    m = {"N": n, "NWord": W.get(n, str(n)), "FullVerifyN": full, "FullVerifyWord": W.get(full, str(full)),
         "PartialVerifyN": part, "PartialVerifyWord": W.get(part, str(part)), "ChannelWrittenYesN": ch, "ChannelWrittenYesWord": W.get(ch, str(ch)),
         "EscYesN": esc_yes, "EscYesWord": W.get(esc_yes, str(esc_yes)), "EscPartialN": esc_part,
         "EscPartialWord": W.get(esc_part, str(esc_part)), "QuotesUnchecked": unchecked}
    write_generated(PAPER / "generated/design/audit.tex", "% Generated by tools/audit_table.py. Do not edit.\n" +
                    "".join(rf"\newcommand{{\wtthAudit{k}}}{{{v}}}" + "\n" for k, v in m.items()))
    md = lambda s: tex_escape(s.replace("`", ""))
    # One page (review 2, M6: the table ran past the page, losing its caption, cutting the CAMEL row and printing the
    # page number over a row). The table sits in a float, which cannot break across pages, so it has to fit: the
    # framework names wrap in a fixed column, the ratings take their natural width under short headers, the evidence
    # column gets the rest at 6 pt gaps, and the evidence prints in the table's own font: about 0.6 of a page.
    gap = r"@{\hspace{6pt}}"
    spec = ("@{}r" + gap + r">{\raggedright\arraybackslash}p{0.14\linewidth}" + gap + "c" + gap + "c" + gap + "c" + gap
            + r">{\raggedright\arraybackslash}X@{}")
    lines = ["% Generated by tools/audit_table.py from data/oss_audit.csv. Do not edit.",
             r"\begin{tabularx}{\linewidth}{" + spec + "}", r"\toprule",
             r"\# & Framework / protocol & Escalation & \shortstack{Peers\\verify} & Receipt & Evidence \\", r"\midrule"]
    for r in rows:
        lines.append(f"{r['id']} & {md(r['framework'])} & {r['escalation_to_human']} & {r['peers_can_verify']} & "
                     f"{r['channel_written_receipt']} & {md(r['evidence'])} \\\\")
    lines += [r"\bottomrule", r"\end{tabularx}"]
    write_generated(PAPER / "generated/design/table_oss_audit.tex", "\n".join(lines) + "\n")
    print(f"audit_table: n={n} full={full} partial={part} channel={ch} escalation yes={esc_yes} partial={esc_part} "
          f"quotes_unchecked={unchecked}")


if __name__ == "__main__":
    main()
