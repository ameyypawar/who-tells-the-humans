"""Write generated/placeholder/macros.placeholder.tex: a grey box for every analysis macro the paper sources use."""
import re
from pathlib import Path

from _common import PAPER, write_generated

OWN = ("wtthDesign", "wtthStim", "wtthAudit")
SRC = [PAPER / "main.tex", PAPER / "cited.tex"] + sorted((PAPER / "sections").rglob("*.tex"))
DEFINING = [PAPER / n for n in ("preamble.tex", "loaders.tex", "main.tex", "cited.tex")]
COMMENT = re.compile(r"(?<!\\)%.*")
USE = re.compile(r"\\(wtth[A-Za-z]+)")
DEF = re.compile(r"\\(?:newcommand|renewcommand|providecommand|def|csdef)\*?\s*\{?\\(wtth[A-Za-z]+)")
NEWIF = re.compile(r"\\newif\\if(wtth[A-Za-z]+)")


def main() -> None:
    defined = {"wtthStatus"}
    for f in DEFINING:
        t = f.read_text(encoding="utf-8")
        defined |= set(DEF.findall(t))
        for n in NEWIF.findall(t):
            defined |= {n, n + "true", n + "false"}
    # branch.tex and the loaders define their own helpers; from branch.tex only the Haiku* references are results macros
    defined |= {"wtthShowAllBranches", "wtthShowAllBranchestrue", "wtthShowAllBranchesfalse", "wtthFinal", "wtthFinaltrue",
                "wtthFinalfalse"}
    used = set()
    for f in SRC:
        used |= set(USE.findall(COMMENT.sub("", f.read_text(encoding="utf-8"))))
    used |= {n for n in USE.findall(COMMENT.sub("", (PAPER / "branch.tex").read_text(encoding="utf-8"))) if n.startswith("wtthHaiku")}
    keys = sorted(n for n in used if not n.startswith(OWN) and n not in defined)
    lines = ["% Generated by tools/make_placeholders.py. Do not edit.",
             "% Every analysis macro the paper sources use, as a grey box. Replaced by generated/analysis/macros*.tex.",
             r"\newcommand{\wtthStatus}{PLACEHOLDER}"]
    lines += [rf"\newcommand{{\{k}}}{{\wtthPH{{{k[4:]}}}}}" for k in keys]
    write_generated(PAPER / "generated/placeholder/macros.placeholder.tex", "\n".join(lines) + "\n")
    print(f"make_placeholders: {len(keys)} macros")


if __name__ == "__main__":
    main()
