"""Write generated/design/references.bib = prereg/references.bib (note fields dropped) + bib/references-added.bib.
Also keeps bib/citations-verified.csv in step (adds missing keys as `pending`; never changes an existing status)."""
import csv
import sys

from _common import PAPER, hashes, resolve_ref, sha256, show, write_generated


def drop_notes(bib: str) -> str:
    out, i = [], 0
    while i < len(bib):
        j = bib.find("note", i)
        # a field start: `note` at the start of a line (after indentation) followed by `=`
        while j != -1 and not (bib[:j].rsplit("\n", 1)[-1].strip() == "" and bib[j + 4:].lstrip().startswith("=")):
            j = bib.find("note", j + 4)
        if j == -1:
            out.append(bib[i:]); break
        out.append(bib[i:bib.rfind("\n", 0, j) + 1])
        k = bib.index("=", j) + 1
        while bib[k] in " \t":
            k += 1
        if bib[k] == "{":
            depth = 0
            while True:
                depth += (bib[k] == "{") - (bib[k] == "}")
                k += 1
                if depth == 0:
                    break
        else:
            while bib[k] not in ",\n":
                k += 1
        if bib[k:k + 1] == ",":
            k += 1
        i = bib.index("\n", k) + 1 if "\n" in bib[k:] else len(bib)
    return "".join(out)


def keys(bib: str) -> list[str]:
    import re
    return re.findall(r"^@\w+\{([^,\s]+),", bib, flags=re.M)


def main() -> None:
    ref, _ = resolve_ref()
    raw = show(ref, "prereg/references.bib")
    if sha256(raw) != hashes(ref)["files"]["references.bib"]:
        sys.exit("build_bib: prereg/references.bib differs from configs/prereg_hashes.json")
    base = drop_notes(raw.decode("utf-8"))
    added = (PAPER / "bib/references-added.bib").read_text(encoding="utf-8")
    ks = keys(base) + keys(added)
    dup = {k for k in ks if ks.count(k) > 1}
    if dup:
        sys.exit(f"build_bib: duplicate keys {sorted(dup)}")
    write_generated(PAPER / "generated/design/references.bib",
                    f"% Generated by tools/build_bib.py: prereg/references.bib at {ref} without note fields, plus bib/references-added.bib.\n"
                    + base + "\n" + added)
    p = PAPER / "bib/citations-verified.csv"
    rows = list(csv.reader(p.open(encoding="utf-8"))) if p.exists() else [["key", "url_opened", "date", "by", "status"]]
    have = {r[0] for r in rows[1:]}
    rows += [[k, "", "", "", "pending"] for k in ks if k not in have]
    with p.open("w", newline="", encoding="utf-8") as f:
        csv.writer(f).writerows(rows)
    print(f"build_bib: {len(ks)} keys, note fields left in output: {'note' in [l.split('=')[0].strip() for l in (PAPER/'generated/design/references.bib').read_text().splitlines()]}")


if __name__ == "__main__":
    main()
